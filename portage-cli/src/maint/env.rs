//! `env-update`: regenerate `${ROOT}/etc/profile.env`, `etc/csh.env`,
//! `etc/environment.d/10-gentoo-env.conf` and the dynamic linker
//! configuration from `${ROOT}/etc/env.d/`.
//!
//! Mirrors portage's behaviour: env.d files named `NN*` are read in sorted
//! order; colon- and space-separated variables accumulate their unique items
//! across files (a file's `COLON_SEPARATED`/`SPACE_SEPARATED` adds to those
//! sets), anything else is last-file-wins. `LDPATH` feeds `etc/ld.so.conf`,
//! and the `ld.so` cache is rebuilt (best-effort when unprivileged).

use std::collections::{BTreeMap, BTreeSet};
use std::iter::Peekable;
use std::str::Chars;

use anyhow::{Context, Result};
use camino::Utf8Path;

/// Variables joined with `:` across env.d files (portage's COLON_SEPARATED)
const COLON_SEPARATED: &[&str] = &[
    "ADA_INCLUDE_PATH",
    "ADA_OBJECTS_PATH",
    "CLASSPATH",
    "INFODIR",
    "INFOPATH",
    "KDEDIRS",
    "LDPATH",
    "MANPATH",
    "PATH",
    "PKG_CONFIG_PATH",
    "PYTHONPATH",
    "ROOTPATH",
];

/// Variables joined with a space (portage's SPACE_SEPARATED)
const SPACE_SEPARATED: &[&str] = &["CONFIG_PROTECT", "CONFIG_PROTECT_MASK"];

const HEADER: &str = "# Autogenerated by em env-update; do not edit (see /etc/env.d).\n";

/// `root`'s env.d files merged in sorted order, as portage does
pub fn merged_env_d(root: &Utf8Path) -> BTreeMap<String, String> {
    let env_d = root.join("etc/env.d");
    let mut names: Vec<String> = match std::fs::read_dir(env_d.as_std_path()) {
        Ok(rd) => rd
            .filter_map(|e| e.ok())
            .filter(|e| e.path().is_file())
            .filter_map(|e| e.file_name().into_string().ok())
            .filter(|n| is_env_d_name(n))
            .collect(),
        // No env.d at all (fresh prefix): nothing to merge.
        Err(_) => Vec::new(),
    };
    names.sort();

    let files = names
        .iter()
        .filter_map(|name| {
            let path = env_d.join(name);
            let bytes = std::fs::read(path.as_std_path()).ok()?;
            parse_env_file(&String::from_utf8_lossy(&bytes))
                .inspect_err(|e| tracing::warn!("env-update: skipping {path}: {e}"))
                .ok()
        })
        .collect();
    merge(files)
}

/// Portage only reads env.d entries that start with two digits.
fn is_env_d_name(name: &str) -> bool {
    let mut chars = name.chars();
    name.chars().count() >= 3
        && chars.next().is_some_and(|c| c.is_ascii_digit())
        && chars.next().is_some_and(|c| c.is_ascii_digit())
        && !name.ends_with('~')
        && !name.ends_with(".bak")
}

/// Fold per-file assignments (in file order) into the final environment.
fn merge(mut files: Vec<BTreeMap<String, String>>) -> BTreeMap<String, String> {
    let mut space: BTreeSet<String> = SPACE_SEPARATED.iter().map(|s| s.to_string()).collect();
    let mut colon: BTreeSet<String> = COLON_SEPARATED.iter().map(|s| s.to_string()).collect();
    for vars in &mut files {
        if let Some(v) = vars.remove("SPACE_SEPARATED") {
            space.extend(v.split_whitespace().map(String::from));
        }
        if let Some(v) = vars.remove("COLON_SEPARATED") {
            colon.extend(v.split_whitespace().map(String::from));
        }
    }

    let mut env = BTreeMap::new();
    // Space first: a variable in both sets is consumed here and stays space-joined.
    for (set, sep) in [(&space, " "), (&colon, ":")] {
        for var in set {
            let mut items: Vec<String> = Vec::new();
            for vars in &mut files {
                let Some(value) = vars.remove(var) else {
                    continue;
                };
                let split: Vec<&str> = if sep == " " {
                    value.split_whitespace().collect()
                } else {
                    value.split(':').collect()
                };
                for item in split {
                    if !item.is_empty() && !items.iter().any(|i| i == item) {
                        items.push(item.to_string());
                    }
                }
            }
            if !items.is_empty() {
                env.insert(var.clone(), items.join(sep));
            }
        }
    }
    for vars in files {
        env.extend(vars);
    }
    env
}

/// One env.d file's assignments, read as unexpanded shell words like portage's
/// `getconfig(expand=False)`; `Err` describes the first syntax error.
fn parse_env_file(content: &str) -> Result<BTreeMap<String, String>, String> {
    let mut words = Words(content.chars().peekable());
    let mut vars = BTreeMap::new();
    while let Some(mut key) = words.next()? {
        if key == "export" {
            let Some(k) = words.next()? else { break };
            key = k;
        }
        match words.next()? {
            Some(eq) if eq == "=" => {}
            other => return Err(format!("expected '=' after {key:?}, found {other:?}")),
        }
        let Some(value) = words.next()? else {
            return Err(format!("no value for {key:?}"));
        };
        if key.starts_with(|c: char| c.is_ascii_digit())
            || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        {
            return Err(format!("invalid variable name {key:?}"));
        }
        vars.insert(key, value);
    }
    Ok(vars)
}

/// POSIX `shlex` tokenizer with portage's config word characters: quotes are
/// removed, `#` starts a comment, and any other character is a token of its own.
struct Words<'a>(Peekable<Chars<'a>>);

impl Words<'_> {
    fn next(&mut self) -> Result<Option<String>, String> {
        let is_space = |c: char| matches!(c, ' ' | '\t' | '\r' | '\n');
        let is_word = |c: char| c.is_ascii_alphanumeric() || "~!@$%*_:;?,./-+{}".contains(c);
        loop {
            match self.0.peek().copied() {
                None => return Ok(None),
                Some(c) if is_space(c) => {
                    self.0.next();
                }
                Some('#') => self.skip_line(),
                Some(c) if !is_word(c) && !matches!(c, '\'' | '"' | '\\') => {
                    self.0.next();
                    return Ok(Some(c.to_string()));
                }
                Some(_) => break,
            }
        }

        let mut token = String::new();
        while let Some(c) = self.0.peek().copied() {
            match c {
                c if is_space(c) => {
                    self.0.next();
                    break;
                }
                '#' => {
                    self.skip_line();
                    break;
                }
                '\'' => {
                    self.0.next();
                    loop {
                        match self.0.next() {
                            None => return Err("no closing quotation".into()),
                            Some('\'') => break,
                            Some(c) => token.push(c),
                        }
                    }
                }
                '"' => {
                    self.0.next();
                    loop {
                        match self.0.next() {
                            None => return Err("no closing quotation".into()),
                            Some('"') => break,
                            Some('\\') => {
                                let e = self.0.next().ok_or("no escaped character")?;
                                if e != '"' && e != '\\' {
                                    token.push('\\');
                                }
                                token.push(e);
                            }
                            Some(c) => token.push(c),
                        }
                    }
                }
                '\\' => {
                    self.0.next();
                    token.push(self.0.next().ok_or("no escaped character")?);
                }
                c if is_word(c) => {
                    self.0.next();
                    token.push(c);
                }
                _ => break,
            }
        }
        Ok(Some(token))
    }

    fn skip_line(&mut self) {
        for c in self.0.by_ref() {
            if c == '\n' {
                break;
            }
        }
    }
}

/// The variables written to the shell environment files: all but `LDPATH`.
fn exported(env: &BTreeMap<String, String>) -> impl Iterator<Item = (&String, &String)> {
    env.iter().filter(|(k, _)| *k != "LDPATH")
}

/// `etc/profile.env` for sh-compatible shells
fn render_profile_env(env: &BTreeMap<String, String>) -> String {
    let mut out = format!("{HEADER}\n");
    for (key, value) in exported(env) {
        // A leading `$` (not `${`) marks an ANSI-C quoted value in env.d.
        match value.strip_prefix('$') {
            Some(rest) if !rest.starts_with('{') => {
                out.push_str(&format!("export {key}=$'{rest}'\n"))
            }
            _ => out.push_str(&format!("export {key}='{value}'\n")),
        }
    }
    out
}

/// `etc/csh.env` for (t)csh
fn render_csh_env(env: &BTreeMap<String, String>) -> String {
    let mut out = format!("{HEADER}\n");
    for (key, value) in exported(env) {
        out.push_str(&format!("setenv {key} '{value}'\n"));
    }
    out
}

/// `etc/environment.d/10-gentoo-env.conf` for systemd user sessions
fn render_environment_d(env: &BTreeMap<String, String>) -> String {
    let mut out = format!("{HEADER}\n");
    // An empty assignment is invalid environment.d syntax.
    for (key, value) in exported(env).filter(|(_, v)| !v.is_empty()) {
        out.push_str(&format!("{key}={value}\n"));
    }
    out
}

/// `etc/ld.so.conf` listing `dirs`
fn render_ld_so_conf(dirs: &[&str]) -> String {
    let mut out = HEADER.to_string();
    for dir in dirs {
        out.push_str(dir);
        out.push('\n');
    }
    out
}

/// An existing `ld.so.conf`'s entries with comments dropped and whitespace
/// collapsed, the form portage compares against `LDPATH` before rewriting it.
fn ld_so_conf_lines(content: &str) -> Vec<String> {
    content
        .lines()
        .map(|line| {
            let words: Vec<&str> = line
                .split_whitespace()
                .take_while(|w| !w.starts_with('#'))
                .collect();
            words.join(" ")
        })
        .filter(|l| !l.is_empty())
        .collect()
}

/// Regenerate the env.d-derived files under `root`, then refresh the `ld.so` cache.
pub fn env_update(root: &Utf8Path) -> Result<()> {
    let env = merged_env_d(root);
    let etc = root.join("etc");
    std::fs::create_dir_all(etc.join("environment.d").as_std_path())
        .context("creating etc/environment.d")?;

    let ldpath: Vec<&str> = env
        .get("LDPATH")
        .map(|v| v.split(':').collect())
        .unwrap_or_default();
    let ld_so_conf = etc.join("ld.so.conf");
    let current = std::fs::read_to_string(ld_so_conf.as_std_path())
        .map(|c| ld_so_conf_lines(&c))
        .unwrap_or_default();
    if current != ldpath {
        std::fs::write(ld_so_conf.as_std_path(), render_ld_so_conf(&ldpath))
            .context("writing ld.so.conf")?;
    }

    for (path, content) in [
        ("profile.env", render_profile_env(&env)),
        (
            "environment.d/10-gentoo-env.conf",
            render_environment_d(&env),
        ),
        ("csh.env", render_csh_env(&env)),
    ] {
        std::fs::write(etc.join(path).as_std_path(), content)
            .with_context(|| format!("writing {path}"))?;
    }

    if !ldpath.is_empty() {
        // Refresh `${root}/etc/ld.so.cache`. Best-effort (glibc only; needs
        // write access). We use the `ldconfig` library rather than shelling to
        // the host binary: it reads each library's ELF arch, so it writes a
        // correct cache even for a foreign-arch `--root` (a cross stage), and
        // doesn't depend on an `ldconfig` being installed/on PATH.
        if let Err(e) = refresh_ld_cache(root) {
            crate::style::warn_line!("env-update: ld.so.cache not refreshed: {e:#}");
        }
    }

    Ok(())
}

/// Rebuild `${root}/etc/ld.so.cache` from `${root}/etc/ld.so.conf` (or the
/// default search dirs)
///
/// Updates the soname symlinks as glibc's `ldconfig` does. Arch-correct
/// for foreign roots: the scanner reads each ELF.
fn refresh_ld_cache(root: &Utf8Path) -> Result<()> {
    use ldconfig::{Cache, SearchPaths};

    // Paths are named as seen inside `root`; the crate resolves them there.
    // A missing config yields no directories, leaving the system ones.
    let search = SearchPaths::from_file("/etc/ld.so.conf", Some(root))?.with_system();
    let cache = Cache::builder()
        .update_symlinks(true)
        .dry_run(false)
        .prefix(root)
        .build(&search)?;
    cache
        .write_to_file(root.join("etc/ld.so.cache"))
        .context("writing ld.so.cache")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    // The C library this test binary has loaded, to populate a scratch root
    // with a real shared object whatever the host architecture.
    fn running_libc() -> Option<std::path::PathBuf> {
        let maps = std::fs::read_to_string("/proc/self/maps").ok()?;
        maps.lines()
            .filter_map(|l| l.split_whitespace().nth(5))
            .find(|p| p.ends_with("/libc.so.6"))
            .map(Into::into)
    }

    fn env(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    #[test]
    fn ld_cache_of_a_foreign_root_lists_paths_inside_that_root() {
        let Some(libc) = running_libc() else { return };
        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        for sub in ["etc/ld.so.conf.d", "opt/extra/lib", "usr/lib64"] {
            std::fs::create_dir_all(root.join(sub)).unwrap();
        }
        // The relative include every distribution config starts with.
        std::fs::write(root.join("etc/ld.so.conf"), "include ld.so.conf.d/*.conf\n").unwrap();
        std::fs::write(root.join("etc/ld.so.conf.d/extra.conf"), "/opt/extra/lib\n").unwrap();
        std::fs::copy(&libc, root.join("opt/extra/lib/libc.so.6")).unwrap();
        std::fs::copy(&libc, root.join("usr/lib64/libc.so.6")).unwrap();

        refresh_ld_cache(root).unwrap();

        let cache = ldconfig::Cache::from_file(root.join("etc/ld.so.cache")).unwrap();
        let paths: Vec<String> = cache.entries().map(|e| e.path).collect();
        // The configured directory and a built-in system one, both as the
        // target sees them, never prefixed with the scratch root.
        assert_eq!(paths, ["/opt/extra/lib/libc.so.6", "/usr/lib64/libc.so.6"]);
    }

    #[test]
    fn merges_env_d_with_portage_semantics() {
        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        let env_d = root.join("etc/env.d");
        std::fs::create_dir_all(&env_d).unwrap();
        std::fs::write(env_d.join("00basic"), "PATH=\"/usr/bin\"\nEDITOR=nano\n").unwrap();
        std::fs::write(
            env_d.join("50extra"),
            "PATH=\"/opt/bin:/usr/bin\"\nEDITOR=vim\nCONFIG_PROTECT=\"/etc/extra\"\nLDPATH=\"/usr/lib64/extra\"\n",
        )
        .unwrap();
        // Not two leading digits, or a backup: ignored.
        std::fs::write(env_d.join("gcc"), "EDITOR=emacs\n").unwrap();
        std::fs::write(env_d.join("99x.bak"), "EDITOR=emacs\n").unwrap();

        env_update(root).unwrap();

        let profile = std::fs::read_to_string(root.join("etc/profile.env")).unwrap();
        assert_eq!(
            profile,
            format!(
                "{HEADER}\nexport CONFIG_PROTECT='/etc/extra'\nexport EDITOR='vim'\nexport PATH='/usr/bin:/opt/bin'\n"
            )
        );
        let ld = std::fs::read_to_string(root.join("etc/ld.so.conf")).unwrap();
        assert_eq!(ld, format!("{HEADER}/usr/lib64/extra\n"));
        assert!(root.join("etc/csh.env").is_file());
        assert!(root.join("etc/environment.d/10-gentoo-env.conf").is_file());
    }

    #[test]
    fn ld_so_conf_left_alone_when_entries_match() {
        let dir = tempfile::tempdir().unwrap();
        let root = Utf8Path::from_path(dir.path()).unwrap();
        std::fs::create_dir_all(root.join("etc/env.d")).unwrap();
        std::fs::write(
            root.join("etc/env.d/00glibc"),
            "LDPATH=\"include ld.so.conf.d/*.conf\"\n",
        )
        .unwrap();
        let hand = "# hand-written\ninclude   ld.so.conf.d/*.conf  # trailing\n\n";
        std::fs::write(root.join("etc/ld.so.conf"), hand).unwrap();

        env_update(root).unwrap();
        assert_eq!(
            std::fs::read_to_string(root.join("etc/ld.so.conf")).unwrap(),
            hand
        );
    }

    #[test]
    fn parses_env_d_like_portage_getconfig() {
        let vars = parse_env_file(
            "# comment\nexport A=\"x y\" B='$q' # tail\nC=a\\ b\"c\\\"\\d\"\nD=\"\"\n",
        )
        .unwrap();
        assert_eq!(
            vars,
            env(&[("A", "x y"), ("B", "$q"), ("C", "a bc\"\\d"), ("D", "")])
        );
        assert!(parse_env_file("A=\"open\n").is_err());
        assert!(parse_env_file("A B\n").is_err());
        assert!(parse_env_file("A=1\n1BAD=z\nB=2\n").is_err());
    }

    #[test]
    fn merge_dedups_lists_and_honours_declared_separators() {
        let files = vec![
            env(&[("PATH", "/a:/b"), ("CONFIG_PROTECT", "/x /y"), ("FOO", "1")]),
            env(&[
                ("PATH", "/b::/c"),
                ("CONFIG_PROTECT", "/y  /z"),
                ("COLON_SEPARATED", "MYPATH"),
                ("MYPATH", "/m"),
                ("FOO", "2"),
            ]),
            env(&[("MYPATH", "/n:/m"), ("GCC_SPECS", "")]),
        ];
        assert_eq!(
            merge(files),
            env(&[
                ("CONFIG_PROTECT", "/x /y /z"),
                ("FOO", "2"),
                ("GCC_SPECS", ""),
                ("MYPATH", "/m:/n"),
                ("PATH", "/a:/b:/c"),
            ])
        );
    }

    #[test]
    fn renders_each_shell_format() {
        let env = env(&[
            ("GCC_SPECS", ""),
            ("LDPATH", "/usr/lib64"),
            ("LESS", "$-R\\n"),
            ("PATH", "/usr/bin:${HOME}/bin"),
        ]);
        assert_eq!(
            render_profile_env(&env),
            format!(
                "{HEADER}\nexport GCC_SPECS=''\nexport LESS=$'-R\\n'\nexport PATH='/usr/bin:${{HOME}}/bin'\n"
            )
        );
        assert_eq!(
            render_csh_env(&env),
            format!(
                "{HEADER}\nsetenv GCC_SPECS ''\nsetenv LESS '$-R\\n'\nsetenv PATH '/usr/bin:${{HOME}}/bin'\n"
            )
        );
        assert_eq!(
            render_environment_d(&env),
            format!("{HEADER}\nLESS=$-R\\n\nPATH=/usr/bin:${{HOME}}/bin\n")
        );
    }
}
